    private readonly Dictionary<string, string> _d;
    public static SourceReviserLangProvider Current => new(UILangProvider.Current.LanguageCode);
    public string LanguageCode { get; }
    public string this[string key] =>
        _d.TryGetValue(key, out var value) ? value :
        IsSharedEnglishKey(key) && Data["en"].TryGetValue(key, out var enVal) ? enVal :
        key;

    private static bool IsSharedEnglishKey(string key) =>
        key.StartsWith("SourceReviser.Option.", StringComparison.Ordinal)
        || key == "SourceReviser.UnknownResolution"
        || key == "SourceReviser.UnknownFrameRate"
        || key == "SourceReviser.OutputFramesUnknown"
        || key.StartsWith("SourceReviser.PatternDescription.Telecine", StringComparison.Ordinal)
        || key.StartsWith("SourceReviser.PatternDescription.FourField", StringComparison.Ordinal)
        || key == "SourceReviser.PatternDescription.EuroPulldown";

    public SourceReviserLangProvider(string languageCode)
    {
        LanguageCode = Data.ContainsKey(languageCode) ? languageCode : "en";
        _d = Data[LanguageCode];
    }
